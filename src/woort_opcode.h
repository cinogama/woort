    // JBCKZ: 向前条件跳转（检查点版本），如果为零则跳转 (Jump Back Checkpoint if Zero)
    //     S8: 条件值栈偏移，有符号 (8位，整数)
    //     U16: 跳转偏移，无符号 (16位)
    //     注: 通过减法实现向前跳转，并触发检查点
