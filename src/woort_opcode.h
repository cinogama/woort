    //     S8: 条件值栈偏移，有符号 (8位，整数)
    //     U16: 跳转偏移，无符号 (16位)
    /*      JFWDZ               |_______1________|___R_ONLY_S8___|_____________U16______________|_______X_______|  */
    // JFWDZ: 向前条件跳转，如果为零则跳转 (Jump Forward if Zero)
    //     S8: 条件值栈偏移，有符号 (8位，整数)
    //     U16: 跳转偏移，无符号 (16位)
