    //     U8: 跳转偏移，无符号 (8位)
    /*      JFWDNEQ             |_______3________|___R_ONLY_S8___|___R_ONLY_S8___|______U8______|_______X_______|  */
    // JFWDNEQ: 向前条件跳转，如果不相等则跳转 (Jump Forward if Not Equal)
    //     S8: 第一个操作数栈偏移，有符号 (8位，整数)
    //     S8: 第二个操作数栈偏移，有符号 (8位，整数)
    //     U8: 跳转偏移，无符号 (8位)
